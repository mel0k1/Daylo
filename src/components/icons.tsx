// Пиксельные иконки пунктов нижней панели: сетка 16×16, заливка currentColor.
// Детали («прорези») рисуются цветом слота var(--slot) поверх заливки —
// так иконка остаётся одноцветной и совпадает с фоном своего квадрата
type Rect = [x: number, y: number, w: number, h: number]

function Pixel({ r, k = [] }: { r: Rect[]; k?: Rect[] }) {
  return (
    <svg viewBox="0 0 16 16" width={14} height={14} shapeRendering="crispEdges" aria-hidden="true">
      {r.map(([x, y, w, h], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} fill="currentColor" />
      ))}
      {k.map(([x, y, w, h], i) => (
        <rect key={`k${i}`} x={x} y={y} width={w} height={h} fill="var(--slot, #6a7280)" />
      ))}
    </svg>
  )
}

